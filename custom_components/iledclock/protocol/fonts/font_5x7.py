# Transpose row-strings (top-to-bottom) into column-major tuples of booleans, matching the
# `Glyph = tuple[tuple[bool, ...], ...]` contract in `fonts/__init__.py`.
FONT_5X7 = {
    char: tuple(
        tuple(rows[row][col] == "#" for row in range(len(rows))) for col in range(len(rows[0]))
    )
    for char, rows in _ROWS.items()
}
for _char in list(FONT_5X7):
    if _char.isupper() and _char.isalpha():
        FONT_5X7[_char.lower()] = FONT_5X7[_char]
